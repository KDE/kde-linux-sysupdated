package main

import (
	"fmt"
	"io"
	"log"
	"os"
	"strings"

	"github.com/coreos/go-systemd/unit"
)

func pathFromUrl(url string) (string, error) {
	if !strings.HasPrefix(url, "http://") && !strings.HasPrefix(url, "https://") {
		return "", fmt.Errorf("invalid URL format: %s", url)
	}

	parts := strings.SplitN(url, "/", 4)
	if len(parts) < 4 {
		return "", fmt.Errorf("invalid URL format: %s", url)
	}

	return "/" + parts[3], nil
}

func main() {
	origFile := "/usr/lib/sysupdate.d/50-root-x86-64-erofs.transfer"
	if _, err := os.Stat(origFile); err != nil {
		log.Fatalln(err)
	}

	file, err := os.Open(origFile)
	if err != nil {
		log.Fatalln(err)
	}
	defer file.Close()

	options, err := unit.Deserialize(file)
	if err != nil {
		log.Fatalln(err)
	}

	var path *string = nil
	for _, option := range options {
		if option.Section == "Source" && option.Name == "Path" {
			p, err := pathFromUrl(option.Value)
			if err != nil {
				log.Fatalln("Failed to get path from URL:", err)
			}
			path = &p
			break
		}
	}
	if path == nil {
		log.Fatalln("No Source Path found in", origFile)
	}

	fmt.Println("Original Source Path:", path)
	newPath := "http://localhost:3129" + *path
	fmt.Println("New Source Path:", newPath)

	newOption := unit.NewUnitOption("Source", "Path", newPath)

	overrideDir := "/run/sysupdate.d/50-root-x86-64-erofs.transfer.d"
	os.MkdirAll(overrideDir, 0755)

	outFile, err := os.Create(overrideDir + "/00-default.conf")
	if err != nil {
		log.Fatalln("Failed to create override file:", err)
	}
	defer outFile.Close()

	outFile.Write([]byte("# This file was automatically generated by kde-linux-sysupdated-redirector\n"))
	_, err = io.Copy(outFile, unit.Serialize([]*unit.UnitOption{newOption}))
	if err != nil {
		log.Fatalln("Failed to write override file:", err)
	}
	fmt.Println("Override file created at", outFile.Name())
}
